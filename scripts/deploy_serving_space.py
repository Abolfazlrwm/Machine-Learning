"""Deploy the ML portfolio serving layer as a Hugging Face Docker Space.

Assembles a staging directory with exactly the paths hf-space-serving/Dockerfile
COPYs (serving layer, RAG source+corpus, stock source, sms-spam with its
committed artifact), creates/reuses the Space (sdk=docker, cpu-basic) and
uploads. The Space's Docker build then pre-bakes the RAG index.

Usage:
    HF_TOKEN=hf_xxx python scripts/deploy_serving_space.py
    python scripts/deploy_serving_space.py --repo-id Abol0pati/ml-portfolio-api
"""
from __future__ import annotations

import argparse
import os
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPACE_DIR = ROOT / "hf-space-serving"

# What the Dockerfile COPYs — keep in sync with it.
COPY_SET = [
    ("serving/__init__.py", "serving/__init__.py"),
    ("serving/app", "serving/app"),
    ("rag-farsi-assistant/src", "rag-farsi-assistant/src"),
    ("rag-farsi-assistant/data", "rag-farsi-assistant/data"),
    ("stock-movement-ml/src", "stock-movement-ml/src"),
    ("sms-spam", "sms-spam"),
]


def build_staging(staging: Path) -> None:
    """Assemble the upload directory next to the Space files."""
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir(parents=True)

    shutil.copy2(SPACE_DIR / "Dockerfile", staging / "Dockerfile")
    shutil.copy2(SPACE_DIR / "README.md", staging / "README.md")

    for src_rel, dst_rel in COPY_SET:
        src, dst = ROOT / src_rel, staging / dst_rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        if src.is_dir():
            shutil.copytree(
                src, dst,
                ignore=shutil.ignore_patterns("__pycache__", "*.pyc", ".pytest_cache"),
            )
        else:
            shutil.copy2(src, dst)

    # The stock service has no committed artifact — it reports "unavailable"
    # (503 with a fix-it hint) in /v1/health instead of crashing the Space.
    (staging / "STAGING.txt").write_text(
        "Generated by scripts/deploy_serving_space.py — do not edit.\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-id", default="Abol0pati/ml-portfolio-api")
    parser.add_argument("--token", default=os.environ.get("HF_TOKEN", ""),
                        help="HF token (or set the HF_TOKEN env var)")
    parser.add_argument("--staging", default=str(SPACE_DIR / "_staging"))
    args = parser.parse_args()

    if not args.token:
        sys_exit = "No token: pass --token hf_... or set the HF_TOKEN env var."
        raise SystemExit(sys_exit)

    from huggingface_hub import HfApi

    staging = Path(args.staging)
    build_staging(staging)

    api = HfApi(token=args.token)
    url = f"https://huggingface.co/spaces/{args.repo_id}"
    print(f"creating/reusing Docker Space {args.repo_id} ...")
    api.create_repo(repo_id=args.repo_id, repo_type="space", space_sdk="docker",
                    private=False, exist_ok=True)
    print(f"uploading {staging} ...")
    api.upload_folder(repo_id=args.repo_id, repo_type="space",
                      folder_path=str(staging),
                      commit_message="ML portfolio REST API — FastAPI + SSE + Prometheus")
    shutil.rmtree(staging)  # keep the repo tree clean
    print(f"done -> {url}  (first build ~5-10 min: it pre-bakes the E5 index)")


if __name__ == "__main__":
    main()
